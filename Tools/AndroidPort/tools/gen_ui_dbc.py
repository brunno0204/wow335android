#!/usr/bin/env python3
"""Column layouts of the client databases for the UI game layer (UiDbcLayouts.inc).

Reads WoW/Source/DB/Rec/*Rec.{h,cpp}: member types from the header, column order from the
SFileReadFile sequence of Read(). Each field becomes {table, field, column, kind} with kind
'i' integer, 'f' float, 's' string offset, 'l' localized string (16 offsets + flags).
Array members add field1..fieldN (and the bare name for element 1). Run from Tools/AndroidPort."""
import glob, os, re

REC = '../../WoW/Source/DB/Rec'
member_re = re.compile(r'/\*\s*[0-9A-Fa-f]+\s*\*/\s*([A-Za-z_][A-Za-z0-9_:<>\s\*]*?)\s+m_([A-Za-z0-9_]+)\s*(?:\[\s*([A-Za-z0-9_]+)\s*\])?\s*;')
# Named array sizes used by the records (WoW/Source/SoundInterface/Types.h).
CONSTANTS = {'NUM_AMBIENCES': 2}
read_re = re.compile(r'SFileReadFile\(\s*file\s*,\s*(&?)\s*([^,]+?)\s*,\s*sizeof\(([^)]*)\)')
out = []
skipped = []
for header in sorted(glob.glob(os.path.join(REC, '*Rec.h'))):
    cpp = header[:-2] + '.cpp'
    if not os.path.exists(cpp):
        continue
    h, c = open(header, encoding='latin-1').read(), open(cpp, encoding='latin-1').read()
    name_match = re.search(r'return\s+"DBFilesClient\\\\([A-Za-z0-9_]+)\.dbc"', c)
    if not name_match:
        continue
    table = name_match.group(1)
    members = {}
    for type_, field, count in member_re.findall(h):
        members[field] = (type_.strip(), (int(count) if count.isdigit() else CONSTANTS.get(count, 1)) if count else 1)
    column, fields, ok = 0, [], True
    reads = read_re.findall(c)
    offset_counts = {}
    for _, target, _ in reads:
        m = re.match(r'([A-Za-z0-9_]+)Offset\[\d+\]$', target.strip())
        if m:
            offset_counts[m.group(1)] = offset_counts.get(m.group(1), 0) + 1
    for amp, target, size in reads:
        target = target.strip()
        m = re.match(r'this->m_([A-Za-z0-9_]+)(?:\[(\d+)\])?$', target)
        if m:
            field, index = m.group(1), m.group(2)
            type_, count = members.get(field, ('int32_t', 1))
            if any(t in type_ for t in ('int8_t', 'char ', 'int16_t', 'bool')) and '*' not in type_:
                ok = False
                break
            kind = 'f' if 'float' in type_ else 'i'
            if 'C3Vector' in type_ or 'C2Vector' in type_ or 'CImVector' in type_:
                ok = False
                break
            if index is not None or (amp and count == 1):
                n = 1
            else:
                n = count
            for k in range(n):
                element = (int(index) if index is not None else k)
                if count > 1:
                    fields.append((field + str(element + 1), column + k, kind))
                    if element == 0:
                        fields.append((field, column + k, kind))
                else:
                    fields.append((field, column + k, kind))
            column += n
            continue
        m = re.match(r'([A-Za-z0-9_]+)Offset(?:\[(\d+)\])?$', target)
        if m:
            field, index = m.group(1), m.group(2)
            if index is None:
                fields.append((field, column, 's'))
            elif offset_counts.get(field) == 16:
                if index == '0':
                    fields.append((field, column, 'l'))
            else:  # plain string array: field1..fieldN
                fields.append((field + str(int(index) + 1), column, 's'))
                if index == '0':
                    fields.append((field, column, 's'))
            column += 1
            continue
        column += 1  # flags and other locals
    expected = re.search(r's_numColumns\s*=\s*(\d+)', h)
    if expected and int(expected.group(1)) != column:
        ok = False
    if not ok:
        skipped.append(table)
        continue
    seen = set()
    for field, col, kind in fields:
        if field in seen:
            continue
        seen.add(field)
        out.append('    {"%s", "%s", %d, \'%s\'},' % (table, field, col, kind))
open('UiDbcLayouts.inc', 'w').write(
    '// Generated by tools/gen_ui_dbc.py from WoW/Source/DB/Rec. Do not edit.\n'
    'struct UiDbcField { const char *table, *field; uint16_t column; char kind; };\n'
    'static const UiDbcField kUiDbcFields[] = {\n' + '\n'.join(out) + '\n};\n')
print(len(out), 'fields;', 'skipped:', ' '.join(skipped))
