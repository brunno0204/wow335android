#!/usr/bin/env python3
"""ui/001_opcodes.lua: client opcode numbers (CMSG_/MSG_) from WoW/Source/Net/Types.h, as the
global table OP for the UI game layer. Run from Tools/AndroidPort."""
import re
text = open('../../WoW/Source/Net/Types.h', encoding='latin-1').read()
pairs = re.findall(r'\b((?:CMSG|MSG)_[A-Z0-9_]+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*,', text)
lines = ['-- Generated by tools/gen_ui_opcodes.py from WoW/Source/Net/Types.h. Do not edit.', 'OP = {']
for name, value in pairs:
    lines.append('  %s = %d,' % (name, int(value, 0)))
lines.append('}')
# SpellCastResult codes -> GlobalStrings token (SMSG_CAST_FAILED -> UI_ERROR_MESSAGE).
magic = open('../../WoW/Source/Magic/Types.h', encoding='latin-1').read()
lines.append('SPELL_FAILED_TOKENS = {')
for name, value in re.findall(r'\b(SPELL_FAILED_[A-Z0-9_]+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*,', magic):
    lines.append('  [%d] = "%s",' % (int(value, 0), name))
lines.append('}')
open('ui/001_opcodes.lua', 'w').write('\n'.join(lines) + '\n')
print(len(pairs), 'opcodes')
