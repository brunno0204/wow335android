#!/usr/bin/env python3
"""Generates ui/000_cvars.lua: default values of every CVar::Register(...) with a literal
default in the decompiled client (WoW/, Engine/). Run from Tools/AndroidPort."""
import glob, re
pattern = re.compile(r'CVar::Register\(\s*"([^"]+)",\s*"(?:[^"\\]|\\.)*",\s*[^,]+,\s*"((?:[^"\\]|\\.)*)"')
defaults = {}
for path in sorted(glob.glob('../../WoW/**/*.cpp', recursive=True) + glob.glob('../../Engine/**/*.cpp', recursive=True)):
    for name, value in pattern.findall(open(path, encoding='latin-1').read()):
        defaults.setdefault(name, value)
lines = ['-- Generated by tools/gen_ui_cvars.py from the CVar::Register defaults of the decompiled client.',
         'local defaults = {']
for name in sorted(defaults, key=str.lower):
    lines.append('  [%s] = %s,' % (repr(name).replace("'", '"'), '"' + defaults[name].replace('\\"', '\\\\"') + '"'))
lines.append('}')
lines.append('__AndroidCVarDefaults = defaults')
open('ui/000_cvars.lua', 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print(len(defaults), 'cvars')
