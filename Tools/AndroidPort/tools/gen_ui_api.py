#!/usr/bin/env python3
"""Lists the original in-game Lua API (global functions registered with
FrameScript_RegisterFunction in WoW/Source, GlueXML-only files excluded) and the method
tables of game frame types, from the decompiled *_Scripts.cpp sources.
Writes Tools/AndroidPort/UiApiNames.inc. Run from the repository root."""
import os, re, sys
root = sys.argv[1] if len(sys.argv) > 1 else '.'
globals_, methods, texts = {}, {}, []
entry = re.compile(r'\{\s*"([A-Za-z_][A-Za-z0-9_]*)"\s*,\s*&?([A-Za-z_][A-Za-z0-9_:]*)\s*\}')
push = re.compile(r'\b(lua_push[a-z]+|lua_rawgeti|lua_gettable|lua_getfield|lua_newtable|lua_createtable)\s*\(\s*L\s*(?:,\s*("(?:[^"\\]|\\.)*")?)?')
KIND = {'lua_pushnumber': 'n', 'lua_pushinteger': 'n', 'lua_pushstring': 's', 'lua_pushlstring': 's',
        'lua_pushfstring': 's', 'lua_pushvfstring': 's'}
bodies = {}
def collect_bodies(text, fname):
    for m in re.finditer(r'(?:int32_t|int)\s+([A-Za-z_][A-Za-z0-9_:]*)\s*\(\s*lua_State\s*\*\s*L\s*\)\s*\{', text):
        depth, i = 1, m.end()
        while depth and i < len(text):
            depth += {'{': 1, '}': -1}.get(text[i], 0)
            i += 1
        bodies[(fname, m.group(1).split('::')[-1])] = text[m.end():i]
        bodies.setdefault(m.group(1).split('::')[-1], text[m.end():i])
def signature(func, fname, api=''):
    if re.match(r'(Is|Has|Can|In)[A-Z]', api):
        return ''  # predicates: nil (false) without data
    key = func.split('::')[-1]
    body = bodies.get((fname, key)) or bodies.get(key)
    if not body:
        return ''
    # Functions that can answer "nothing" (return 0) model absent data: the stub returns nil.
    # (usage errors, luaL_error + return 0, do not count).
    plain = re.sub(r'luaL_error\s*\((?:[^;]|;(?!\s*return))*?\)\s*;\s*return\s+0\s*;', '', body)
    if re.search(r'\breturn\s+0\s*;', plain):
        return ''
    best, where = 0, -1
    for m in re.finditer(r'\breturn\s+(\d+)\s*;', body):
        if int(m.group(1)) >= best:
            best, where = int(m.group(1)), m.start()
    if best <= 0 or best > 16:
        return ''
    # Pushes of this return's path: after the previous return statement, first N in order
    # (later ones are usually the else-branch alternatives of the same value).
    start = 0
    for m in re.finditer(r'\breturn\b[^;]*;', body[:where]):
        start = m.end()
    pushes = push.findall(body[start:where])
    # Branches that push nil/false for the same value: absent data is the safe answer.
    if len(pushes) > best and any(p in ('lua_pushnil', 'lua_pushboolean') for p, _ in pushes):
        return ''
    values = []
    for p, literal in pushes:
        kind = KIND.get(p, 'x')
        if kind == 'n':
            values.append('0')
        elif kind == 's':
            values.append(literal if literal and '\\' not in literal else '""')
        else:
            values.append('nil')
    values = values[:best]
    values = values + ['nil'] * (best - len(values))
    while values and values[-1] == 'nil':
        values.pop()
    return ','.join(values)
for base, _, files in os.walk(os.path.join(root, 'WoW', 'Source')):
    if os.sep + 'Glue' in base:
        continue
    for name in files:
        if not name.endswith('.cpp'):
            continue
        text = open(os.path.join(base, name), encoding='latin-1').read()
        collect_bodies(text, name)
        texts.append((name, text))
for name, text in texts:
        registered = set(re.findall(r'FrameScript_RegisterFunction\(\s*([A-Za-z_][A-Za-z0-9_]*)\[', text))
        for array in re.finditer(r'(?:static\s+)?(?:const\s+)?FrameScript_Method\s+([A-Za-z_][A-Za-z0-9_]*)\s*\[[^\]]*\]\s*=\s*\{(.*?)\n\};', text, re.S):
            pairs = entry.findall(array.group(2))
            if array.group(1) in registered:
                for n, f in pairs:
                    globals_.setdefault(n, signature(f, name, n))
            else:
                target = methods.setdefault(name.replace('_Scripts.cpp', ''), {})
                for n, f in pairs:
                    target.setdefault(n, signature(f, name, n))
out = ['// Generated by tools/gen_ui_api.py from the decompiled client. Do not edit.',
       '// Global in-game Lua API: "Name:returns" (original FrameScript_RegisterFunction tables).',
       '// returns: Lua values a stub gives back, after the largest return of the original',
       '// implementation (numbers 0, strings "" or the literal pushed, others nil); empty when',
       '// the original can return nothing.',
       'static const char *const kOriginalGlobalApi[] = {']
out += ['    "%s:%s",' % (n, globals_[n].replace('\\', '\\\\').replace('"', '\\"')) for n in sorted(globals_)]
out += ['};']
out += ['// Methods of game frame types created as plain frames here (tooltip, minimap, cooldown, models).',
        'static const char *const kOriginalFrameMethods[] = {']
names = {}
for k, v in methods.items():
    for n, sig in v.items():
        names.setdefault(n, sig)
out += ['    "%s:%s",' % (n, names[n].replace('\\', '\\\\').replace('"', '\\"')) for n in sorted(names)]
out += ['};']
open(os.path.join(root, 'Tools', 'AndroidPort', 'UiApiNames.inc'), 'w').write('\n'.join(out) + '\n')
print(len(globals_), 'globals;', ', '.join('%s:%d' % (k, len(v)) for k, v in sorted(methods.items()) if v))
